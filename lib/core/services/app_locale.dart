import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// App-wide language provider. Persists the choice and exposes translated
/// strings via [t]. Languages: English, Hindi, Kannada, Tamil, Telugu,
/// Bengali, Marathi.
class AppLocale extends ChangeNotifier {
  static const List<String> codes = ['en', 'hi', 'kn', 'ta', 'te', 'bn', 'mr'];
  static const Map<String, String> names = {
    'en': 'English',
    'hi': 'हिन्दी',
    'kn': 'ಕನ್ನಡ',
    'ta': 'தமிழ்',
    'te': 'తెలుగు',
    'bn': 'বাংলা',
    'mr': 'मराठी',
  };

  String code = 'en';

  AppLocale() {
    _load();
  }

  Future<void> _load() async {
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getString('app_language');
    if (saved != null && codes.contains(saved)) {
      code = saved;
      notifyListeners();
    }
  }

  Future<void> setLanguage(String newCode) async {
    if (!codes.contains(newCode)) return;
    code = newCode;
    notifyListeners();
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('app_language', newCode);
  }

  /// Translate a key. Falls back to the English string, then the key itself.
  String t(String key) {
    final lang = _strings[code];
    if (lang != null && lang.containsKey(key)) return lang[key]!;
    return _strings['en']?[key] ?? key;
  }
}

